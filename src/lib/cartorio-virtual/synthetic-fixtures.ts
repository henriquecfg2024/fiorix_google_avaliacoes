export function isAmbienteSinteticoPermitido(
  env: Record<string, string | undefined> = process.env
): boolean {
  if (env.NODE_ENV === "production") {
    return false;
  }
  if (env.NODE_ENV === "test") {
    return true;
  }
  return env.CARTORIO_VIRTUAL_SANDBOX === "true";
}

