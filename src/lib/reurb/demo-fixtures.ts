function makeDerivs(
  startMat: number,
  count: number,
  dataAbertura: string | null,
  dataRegistro: string | null,
  tipoInteresse: number,
  extra?: { includeUntitledFrom?: number; missingAberturaLast?: boolean }
) {
  return Array.from({ length: count }, (_, idx) => {
    const mat = startMat + idx;
    const isUntitled =
      extra?.includeUntitledFrom !== undefined && idx >= extra.includeUntitledFrom;
    const hideAbertura = Boolean(extra?.missingAberturaLast && idx === count - 1);
    return {
      matriculaDerivada: mat,
      complMatricula: null,
      dataAbertura: hideAbertura ? null : dataAbertura,
      dataRegistro: isUntitled ? null : dataRegistro,
      tipoInteresse,
      incluirNoJson: true,
      ehAreaPublica: false,
      ehCondominioIntermediario: false,
      categoriaArea: 'UNIDADE_AUTONOMA',
      vinculoMetodo: 'FILIACAO_DIRETA',
      motivoExclusao: null,
      fonteOcr: `Matrícula ${mat} — lote residencial autônomo`,
    };
  });
}

